%% PHOENIX SoC - PRE-RTL ARCHITECTURE MODEL (MATLAB version of phoenix_model_v2.py)
% Runs the fault-injection campaign on the Phoenix architecture model and compares the
% results with the Python model.
%
% HOW TO RUN: open this file in MATLAB, set the three settings below, press "Run" (F5).
%
% What happens:
%   1. Builds the test program and runs it once with no fault (the reference "answer sheet").
%   2. Static checks of the voter, the address decoder and the memory error code.
%   3. Fault-injection campaign: every run injects one fault scenario and is marked
%      against the reference. Done BEFORE (no extra mechanisms) and AFTER
%      (scrub every 400 cycles, watchdog 300 cycles, SECDED on data memory).
%   4. Prints the results, compares them with Python, saves a .mat file and figures.

clear; clc;

%% ------------------------------------------------------------------ SETTINGS
SETTINGS.mode     = 'replay';  % 'replay': the exact faults of the Python run (data/*.csv),
                               %           so every run can be compared with Python one by one
                               % 'fresh' : new random faults generated by MATLAB
SETTINGS.fraction = 0.1;       % share of the runs to do. 1.0 = all 68,400 runs (same numbers
                               % as the report); 0.1 = a quick check (about a tenth of the time)
SETTINGS.parallel = true;      % true: use all CPU cores if the Parallel Computing Toolbox exists
SETTINGS.seed     = 2026;      % random seed for 'fresh' mode and the static checks

%% ------------------------------------------------------------------ SETUP
here = fileparts(mfilename('fullpath'));
if isempty(here), here = pwd; end
addpath(here);
dataDir = fullfile(here, 'data');
outDir  = fullfile(here, 'results'); if ~exist(outDir, 'dir'), mkdir(outDir); end
rng(SETTINGS.seed);
C = phx_const();
imem = phx_build_program(C);
L = phx_labels();
BEFORE = struct('scrub', 0,   'wdt', 0,   'ecc', 0);
AFTER  = struct('scrub', 400, 'wdt', 300, 'ecc', 1);
workers = 0;                                    % 0 = run in this MATLAB session only
if SETTINGS.parallel && exist('gcp', 'file') == 2
    try
        p = gcp; workers = p.NumWorkers;          % starts the parallel pool (takes ~30 s once)
    catch
        workers = 0;
    end
end
fprintf('Phoenix pre-RTL model, MATLAB version | mode %s | fraction %g | workers %d\n\n', ...
        SETTINGS.mode, SETTINGS.fraction, workers);

%% ------------------------------------------------------------------ 1. REFERENCE RUN
golden = phx_golden(C, imem);
fprintf('Reference run: %d cycles, %d writes to memory and peripherals\n', golden.cycles, size(golden.trace, 1));
gfile = fullfile(dataDir, 'golden.csv');
if exist(gfile, 'file')
    P = csvread(gfile, 1, 0);
    fprintf('Reference identical to the Python reference: %s\n\n', phx_yesno(isequal(P, golden.trace)));
end

%% ------------------------------------------------------------------ 2. STATIC CHECKS
S = phx_static_checks(C, 20000, 200000, 100);
fprintf('STATIC CHECKS\n');
fprintf('  Voter: correct value passed in %d / %d cases, faulty core named in %d / %d\n', ...
        S.voter_masked, S.voter_trials, S.voter_located, S.voter_trials);
fprintf('  Decoder: %d random addresses, every one maps to one region or to the error target: %s\n', ...
        S.decode_trials, phx_yesno(S.decode_ok));
fprintf('  SECDED: %d / %d single-bit errors corrected, %d / %d double-bit errors detected\n\n', ...
        S.ecc_single_ok, S.ecc_single, S.ecc_double_ok, S.ecc_double);

%% ------------------------------------------------------------------ 3. CAMPAIGN
% key, label, full number of runs, configurations to run
EXP = { 'core',     'One bit flip in one core',              10000, {'before','after','single'};
        'mem1',     'One bit flip in a data-memory word',     4000, {'before','after','single'};
        'mem2',     'Two bit flips in one data-memory word',  1000, {'before','after'};
        'dbl_far',  'Two cores hit at independent times',     3000, {'before','after'};
        'dbl_near', 'Two cores hit within 3 cycles',          3000, {'before','after'} };
R = struct();
tAll = tic;
for e = 1:size(EXP, 1)
    key = EXP{e, 1}; n = max(1, round(EXP{e, 3} * SETTINGS.fraction));
    if strcmp(SETTINGS.mode, 'replay')
        F = phx_load_faults(fullfile(dataDir, ['faults_' key '.csv']), n);
    else
        F = phx_make_faults(key, n, golden.cycles);
    end
    for c = 1:numel(EXP{e, 4})
        cname = EXP{e, 4}{c};
        switch cname
            case 'before', cfg = BEFORE; nc = 3; mx = 40000;
            case 'after',  cfg = AFTER;  nc = 3; mx = 40000;
            otherwise,     cfg = BEFORE; nc = 1; mx = 12000;
        end
        t0 = tic;
        out = phx_campaign(F, cfg, nc, [], mx, C, imem, golden, workers);
        R.(key).(cname) = out;
        R.(key).label = EXP{e, 2};
        fprintf('[%6.0f s] %-40s %-6s %6d runs (%.1f s)\n', toc(tAll), EXP{e, 2}, cname, n, toc(t0));
    end
end
% permanent fault
n = max(1, round(200 * SETTINGS.fraction));
if strcmp(SETTINGS.mode, 'replay')
    PM = csvread(fullfile(dataDir, 'faults_perm.csv'), 1, 0); PM = PM(1:n, 2:3);
else
    bits = [3 4 5 9 13 20]; PM = [randi([0 2], n, 1), bits(randi(6, n, 1))'];
end
for cname = {'before', 'after'}
    if strcmp(cname{1}, 'before'), cfg = BEFORE; else, cfg = AFTER; end
    out = struct('outcome', zeros(1, n), 'latency', -ones(1, n), 'recovery', -ones(1, n), 'cycles', zeros(1, n));
    for i = 1:n
        r = phx_run(zeros(0, 5), cfg, 3, PM(i, :), 40000, C, imem, golden);
        out.outcome(i) = r.outcome; out.cycles(i) = r.cycles;
    end
    R.perm.(cname{1}) = out; R.perm.label = 'Permanent fault in one core';
end
fprintf('[%6.0f s] Permanent fault: %d runs\n', toc(tAll), n);
% scrub-period sweep
n = max(1, round(2000 * SETTINGS.fraction));
if strcmp(SETTINGS.mode, 'replay')
    F = phx_load_faults(fullfile(dataDir, 'faults_sweep.csv'), n);
else
    F = phx_make_faults('core', n, golden.cycles);
end
periods = [0 800 400 200 100 50];
SW = struct('period', periods, 'latent', zeros(1, 6), 'overhead', zeros(1, 6), 'out', {cell(1, 6)});
for k = 1:6
    cfg = struct('scrub', periods(k), 'wdt', 300, 'ecc', 1);
    SW.out{k} = phx_campaign(F, cfg, 3, [], 40000, C, imem, golden, workers);
    SW.latent(k) = 100 * mean(SW.out{k}.outcome == C.O_LAT);
    ff = phx_run(zeros(0, 5), cfg, 3, [], 40000, C, imem, golden);
    SW.overhead(k) = 100 * (ff.cycles - golden.cycles) / golden.cycles;
end
fprintf('[%6.0f s] Scrub-period sweep: %d runs x 6 periods\n\n', toc(tAll), n);

%% ------------------------------------------------------------------ 4. RESULTS
keys = [EXP(:, 1)' {'perm'}];
fprintf('RESULTS (share of runs, %%)\n');
for e = 1:numel(keys)
    key = keys{e}; fprintf('\n%s\n', R.(key).label);
    for cname = {'single', 'before', 'after'}
        if ~isfield(R.(key), cname{1}), continue; end
        o = R.(key).(cname{1}).outcome; s = '';
        for k = 1:10
            if any(o == k), s = [s sprintf('%s: %.1f%%, ', L{k}, 100 * mean(o == k))]; end %#ok<AGROW>
        end
        fprintf('   %-7s %s\n', cname{1}, s(1:end-2));
    end
end

% ---- comparison with Python (replay mode only)
if strcmp(SETTINGS.mode, 'replay')
    fprintf('\nCOMPARISON WITH THE PYTHON MODEL (same faults, run by run)\n');
    fprintf('   %-40s %-7s %8s %10s\n', 'Experiment', 'config', 'runs', 'identical');
    tot = 0; same = 0;
    for e = 1:numel(keys)
        key = keys{e};
        for cname = {'single', 'before', 'after'}
            if ~isfield(R.(key), cname{1}), continue; end
            o = R.(key).(cname{1}).outcome;
            P = csvread(fullfile(dataDir, ['python_' key '_' cname{1} '.csv']), 1, 0);
            m = sum(o(:) == P(1:numel(o), 2)); tot = tot + numel(o); same = same + m;
            fprintf('   %-40s %-7s %8d %9.1f%%\n', R.(key).label, cname{1}, numel(o), 100 * m / numel(o));
        end
    end
    fprintf('   All runs: %d of %d identical to Python (%.2f%%)\n', same, tot, 100 * same / tot);
end

% ---- latency (one flip in one core)
for cname = {'before', 'after'}
    lat = R.core.(cname{1}).latency; lat = sort(lat(lat >= 0));
    if ~isempty(lat)
        fprintf('\nDetection latency, one flip in one core, %s: median %g, 90th percentile %g, max %g cycles', ...
                cname{1}, median(lat), lat(max(1, floor(0.9 * numel(lat)))), lat(end));
    end
end
fprintf('\n\nScrub-period sweep:  period  hidden faults left  extra run time\n');
for k = 1:6
    fprintf('                     %6s  %17.1f%%  %13.1f%%\n', phx_period_name(periods(k)), SW.latent(k), SW.overhead(k));
end

%% ------------------------------------------------------------------ 5. SAVE AND PLOT
save(fullfile(outDir, 'phoenix_matlab_results.mat'), 'R', 'SW', 'S', 'golden', 'SETTINGS');
phx_plot_results(R, SW, C, outDir);
fprintf('\nSaved results and figures in %s\nTotal time %.0f s\n', outDir, toc(tAll));
